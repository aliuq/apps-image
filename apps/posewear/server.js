/** Parse the Cloudflare Pages `_headers` file generated by the upstream build. */
function parseHeaderRules(file) {
  try {
    const rules = []
    let current
    for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
      const line = raw.trimEnd()
      if (!line || line.startsWith('#'))
        continue
      if (!/^\s/.test(line)) {
        current = { pattern: line.trim(), headers: [] }
        rules.push(current)
        continue
      }
      const colon = line.indexOf(':')
      const name = colon < 0 ? '' : line.slice(0, colon).trim().toLowerCase()
      if (current && HEADER_NAME.test(name))
        current.headers.push([name, line.slice(colon + 1).trim()])
    }
    return rules
  }
  catch {
    return []
  }
}

const HEADER_RULES = parseHeaderRules(path.join(ROOT, '_headers'))

// Cloudflare Pages 的 `_headers` 允许单个 `*` 通配符出现在路径任意位置，
// 贪婪匹配任意字符。按前后缀还原，避免把 `/icon-*`、`/sitemap*` 当成字面量。
function matchesHeaderPattern(pattern, pathname) {
  const splat = pattern.indexOf('*')
  if (splat < 0)
    return pathname === pattern
  const prefix = pattern.slice(0, splat)
  const suffix = pattern.slice(splat + 1)
  return pathname.length >= prefix.length + suffix.length
    && pathname.startsWith(prefix)
    && pathname.endsWith(suffix)
}

function applyHeaderRules(res, pathname) {
  for (const rule of HEADER_RULES) {
    if (!matchesHeaderPattern(rule.pattern, pathname))
      continue
    for (const [name, value] of rule.headers) {
      if (name === 'content-security-policy') {
        // The upstream policy is written for HTTPS. Docker deployments commonly
        // run on plain HTTP, where upgrading same-origin requests breaks the site.
        res.setHeader(name, value.replace(/;\s*upgrade-insecure-requests/gi, ''))
      }
      else {
        res.setHeader(name, value)
      }
    }
  }
}

function sendJson(res, status, message) {
  const body = JSON.stringify({ error: { message } })
  res.writeHead(status, { 'cache-control': 'no-store', 'content-length': Buffer.byteLength(body), 'content-type': 'application/json; charset=utf-8' })
  res.end(body)
}

function sendNotFound(req, res, pathname) {
  applyHeaderRules(res, pathname)
  res.writeHead(404, { 'cache-control': 'no-cache', 'content-length': NOT_FOUND.length, 'content-type': 'text/html; charset=utf-8' })
  res.end(req.method === 'HEAD' ? undefined : NOT_FOUND)
}

/** 解析 Accept-Encoding；gzip;q=0 表示客户端明确拒绝 gzip。 */
function acceptsGzip(header) {
  const value = String(header || '').toLowerCase()
  return /\bgzip\b/.test(value) && !/\bgzip\s*;\s*q=0(?:\.0*)?\s*(?:,|$)/.test(value)
}

async function serveStatic(req, res, pathname) {
  if (req.method !== 'GET' && req.method !== 'HEAD')
    return res.writeHead(405, { allow: 'GET, HEAD' }).end()
  if (pathname.startsWith('/.'))
    return sendNotFound(req, res, pathname)

  let decoded
  try {
    decoded = decodeURIComponent(pathname)
  }
  catch {
    return res.writeHead(400).end()
  }
  if (decoded.includes('\0'))
    return res.writeHead(400).end()

  let file = path.resolve(ROOT, `.${decoded}`)
  const rel = path.relative(ROOT, file)
  if (
    rel.startsWith('..')
    || path.isAbsolute(rel)
    || rel.split(path.sep).some(part => part.startsWith('.'))
    || rel === '_headers'
    || rel === 'functions'
    || rel.startsWith(`functions${path.sep}`)
  ) {
    return sendNotFound(req, res, pathname)
  }

  let stat
  try {
    stat = await fsp.stat(file)
  }
  catch {
    return sendNotFound(req, res, pathname)
  }

  if (stat.isDirectory()) {
    if (!pathname.endsWith('/')) {
      const search = new URL(req.url, 'http://localhost').search
      return res.writeHead(301, { location: `${pathname}/${search}` }).end()
    }
    file = path.join(file, 'index.html')
    try {
      stat = await fsp.stat(file)
    }
    catch {
      return sendNotFound(req, res, pathname)
    }
  }

  const injected = file === INDEX_FILE && CLIENT_TIMEOUT !== null
    ? Buffer.from((await fsp.readFile(file, 'utf8')).replace('</head>', `${TMO_SCRIPT}</head>`))
    : null
  const size = injected ? injected.length : stat.size
  const type = MIME[path.extname(file).toLowerCase()] || 'application/octet-stream'
  const compressible = /^(?:text\/|application\/(?:json|javascript|manifest\+json|xml))/.test(type)
  applyHeaderRules(res, pathname)
  // 304 也必须携带 200 会发送的 Cache-Control / Vary（RFC 9110）。
  if (compressible)
    res.setHeader('vary', 'accept-encoding')
  if (!res.hasHeader('cache-control'))
    res.setHeader('cache-control', 'public, max-age=600')
  const etag = `W/"${size.toString(16)}-${Math.floor(stat.mtimeMs).toString(16)}"`
  res.setHeader('etag', etag)
  res.setHeader('last-modified', stat.mtime.toUTCString())
  if (req.headers['if-none-match'] === etag)
    return res.writeHead(304).end()

  const useGzip = compressible && size > 1024 && req.method !== 'HEAD' && acceptsGzip(req.headers['accept-encoding'])
  res.setHeader('content-type', type)
  if (useGzip) {
    const gz = await gzip(injected ?? await fsp.readFile(file))
    res.setHeader('content-encoding', 'gzip')
    res.setHeader('content-length', gz.length)
    res.writeHead(200)
    res.end(gz)
    return
  }
  res.setHeader('content-length', size)
  res.writeHead(200)
  if (req.method === 'HEAD') {
    res.end()
    return
  }
  if (injected) {
    res.end(injected)
    return
  }
  await pipeline(fs.createReadStream(file), res)
}

function sameSite(req) {
  const host = req.headers.host
  if (!host)
    return false
  for (const name of ['origin', 'referer']) {
    const value = req.headers[name]
    if (!value)
      continue
    try {
      return new URL(value).host.toLowerCase() === host.toLowerCase()
    }
    catch {
      return false
    }
  }
  return false
}

function normalizeIp(value) {
  const ip = String(value || '').trim()
  if (!net.isIP(ip))
    return ''
  const mapped = ip.match(/^::ffff:(\d+\.\d+\.\d+\.\d+)$/i)
  return mapped ? mapped[1] : ip
}

function isPrivateAddress(ip) {
  const family = net.isIP(ip)
  return Boolean(family) && PRIVATE_RANGES.check(ip, family === 4 ? 'ipv4' : 'ipv6')
}

function clientIp(req) {
  const peer = normalizeIp(req.socket.remoteAddress)
  const forced = TRUST_PROXY === '1' || TRUST_PROXY === 'true'
  const never = TRUST_PROXY === '0' || TRUST_PROXY === 'false'
  if (!peer || never || (!forced && !isPrivateAddress(peer)))
    return peer || '0'
  // 只取最右侧（离本站最近）的 XFF，避免客户端自行追加伪造。
  const candidates = [
    req.headers['cf-connecting-ip'],
    ...String(req.headers['x-forwarded-for'] || '').split(',').reverse(),
    req.headers['x-real-ip'],
  ]
  for (const candidate of candidates) {
    const ip = normalizeIp(candidate)
    if (ip)
      return ip
  }
  return peer
}

/** 判断目标是否属于本机、局域网等非公网地址（不做 DNS 解析）。 */
function isPrivateHost(hostname) {
  let host = String(hostname || '').trim().toLowerCase().replace(/\.$/, '')
  if (host.startsWith('[') && host.endsWith(']'))
    host = host.slice(1, -1)
  if (!host)
    return false
  if (host === 'localhost' || PRIVATE_SUFFIXES.some(suffix => host.endsWith(suffix)))
    return true
  if (PRIVATE_ALLOWLIST.some(entry => host === entry || host.endsWith(`.${entry}`)))
    return true
  if (net.isIP(host))
    return isPrivateAddress(host)
  // 单标签主机名（Docker Compose/K8s 服务名等）不可能是公网 DNS 名。
  return !host.includes('.')
}

const RATE_WINDOW = 60_000
const RATE_MAX_KEYS = 20_000
const API_LIMIT = 20
const IMAGE_LIMIT = 40
const rate = new Map()
setInterval(() => {
  const now = Date.now()
  for (const [key, entry] of rate) {
    if (now - entry.start >= RATE_WINDOW)
      rate.delete(key)
  }
}, RATE_WINDOW).unref()

function isRateLimited(ip, kind) {
  const now = Date.now()
  const key = `${kind}|${ip}`
  let entry = rate.get(key)
  if (!entry || now - entry.start >= RATE_WINDOW) {
    entry = { start: now, count: 0 }
    rate.set(key, entry)
  }
  entry.count += 1
  if (rate.size > RATE_MAX_KEYS) {
    for (const [k, v] of rate) {
      if (now - v.start >= RATE_WINDOW)
        rate.delete(k)
    }
    if (rate.size > RATE_MAX_KEYS) {
      rate.clear()
      rate.set(key, entry)
    }
  }
  return entry.count > (kind === 'image' ? IMAGE_LIMIT : API_LIMIT)
}

function proxyHeaders(req) {
  const headers = {}
  for (const [name, value] of Object.entries(req.headers)) {
    const key = name.toLowerCase()
    if (
      DROP_HEADERS.has(key)
      || key.startsWith('cf-')
      || key.startsWith('proxy-')
      || key.startsWith('x-forwarded-')
      || key.startsWith('x-proxy-')
      || key === 'forwarded'
      || (key === 'content-length' && req.method !== 'POST')
    ) {
      continue
    }
    if (value !== undefined)
      headers[name] = value
  }
  return headers
}

/** 客户端取消或连接断开时中止上游请求。 */
function abortOnDisconnect(req, res, controller) {
  req.on('aborted', () => controller.abort())
  res.on('close', () => {
    if (!res.writableEnded)
      controller.abort()
  })
}

/**
 * 发起上游请求。用 node:http(s) 而非 fetch，避免 undici 内置的 5 分钟
 * headers/body 超时，确保 POSEWEAR_*_TIMEOUT=0 时真正不超时。
 */
function upstreamRequest(target, { method, headers, body, signal }) {
  return new Promise((resolve, reject) => {
    const transport = target.protocol === 'https:' ? https : http
    const useExpect = Boolean(body) && String(headers?.expect || '').toLowerCase() === '100-continue'
    let sent = false
    let settled = false
    let timer = null
    const finish = (error, response) => {
      settled = true
      clearTimeout(timer)
      if (error)
        reject(error)
      else
        resolve(response)
    }
    const upstream = transport.request(target, { method, headers, signal }, response => finish(null, response))
    upstream.on('error', error => finish(error))
    if (!body) {
      upstream.end()
      return
    }
    body.on('error', error => upstream.destroy(error))
    const sendBody = () => {
      if (sent || settled)
        return
      sent = true
      clearTimeout(timer)
      body.pipe(upstream)
    }
    if (useExpect) {
      upstream.once('continue', sendBody)
      timer = setTimeout(sendBody, 1_000)
    }
    else {
      sendBody()
    }
  })
}

/**
 * 拒绝编码分隔符、控制字符和解码后的 . / .. 段；上游若自行解码路径，
 * 这些字符可能让请求逃出 API 路径白名单。
 */
function safeTargetPath(pathname) {
  if (/%2f|%5c|%00/i.test(pathname))
    return false
  try {
    const decoded = decodeURIComponent(pathname)
    return !decoded.includes('\\')
      && ![...decoded].some(char => char.charCodeAt(0) < 0x20 || char.charCodeAt(0) === 0x7F)
      && !decoded.split('/').some(part => part === '.' || part === '..')
  }
  catch {
    return false
  }
}

/** 统一的代理出口：超时、客户端断开、状态/响应头转发和错误映射。 */
async function relay(req, res, target, {
  timeout,
  headers,
  body,
  copy = ['content-type'],
  extra = {},
  validate,
  timeoutMessage,
  failureMessage,
}) {
  const controller = new AbortController()
  const timer = timeout > 0 ? setTimeout(() => controller.abort(), timeout) : null
  abortOnDisconnect(req, res, controller)
  try {
    const upstreamHeaders = body ? { ...headers, expect: '100-continue' } : headers
    const upstream = await upstreamRequest(target, { method: req.method, headers: upstreamHeaders, body, signal: controller.signal })
    if (validate && !validate(upstream)) {
      upstream.destroy()
      return sendJson(res, 502, failureMessage)
    }
    const responseHeaders = { 'cache-control': 'no-store', ...extra }
    for (const name of copy) {
      const value = upstream.headers[name]
      if (value !== undefined)
        responseHeaders[name] = value
    }
    res.writeHead(upstream.statusCode, responseHeaders)
    await pipeline(upstream, res)
  }
  catch (error) {
    if (res.headersSent)
      return res.destroy()
    const timedOut = error.name === 'AbortError'
    sendJson(res, timedOut ? 504 : 502, timedOut ? timeoutMessage : failureMessage)
  }
  finally {
    clearTimeout(timer)
  }
}

async function handleProxy(req, res) {
  if (req.method !== 'GET' && req.method !== 'POST')
    return sendJson(res, 405, '只支持 GET / POST')
  if (!sameSite(req))
    return sendJson(res, 403, '只接受本站页面发起的请求')

  let target
  try {
    target = new URL(String(req.headers['x-target-url'] || ''))
  }
  catch {
    return sendJson(res, 400, '缺少或无效的 x-target-url')
  }
  if (target.username || target.password)
    return sendJson(res, 400, '目标地址不能带账号密码')

  // 公网目标只走 https；本机/局域网目标允许 http。
  const official = OFFICIAL_HOSTS.some(r => r.test(target.hostname))
  const internal = isPrivateHost(target.hostname)
  const protocolOk = internal ? /^https?:$/.test(target.protocol) : target.protocol === 'https:'
  if (!protocolOk)
    return sendJson(res, 400, internal ? '目标地址必须是 http/https 地址' : '公网目标地址必须是 https 地址')

  const ip = clientIp(req)
  if (req.headers['x-proxy-kind'] === 'image') {
    if (req.method !== 'GET')
      return sendJson(res, 405, '图片下载只支持 GET')
    if (!IMAGE_HOSTS.some(r => r.test(target.hostname)))
      return sendJson(res, 403, '该图片地址不在允许范围内')
    if (isRateLimited(ip, 'image'))
      return sendJson(res, 429, '请求过于频繁，请稍后再试')
    return relay(req, res, target, {
      timeout: IMAGE_TIMEOUT,
      copy: ['content-type', 'content-length', 'content-range'],
      extra: { 'x-content-type-options': 'nosniff' },
      validate: upstream => upstream.statusCode >= 200 && upstream.statusCode < 300
        && /^image\//i.test(String(upstream.headers['content-type'] || '')),
      timeoutMessage: '图片下载超时',
      failureMessage: '结果图片下载失败',
    })
  }

  const custom = req.headers['x-proxy-custom'] === '1'
  if (!official && !custom && !internal)
    return sendJson(res, 403, '该地址不是官方接口；自定义中转需在设置中选择「自定义」')
  const targetPath = target.pathname.replace(/\/+$/, '')
  if (!safeTargetPath(target.pathname) || (official ? !API_PATH.test(targetPath) : !CUSTOM_PATH.test(targetPath)))
    return sendJson(res, 403, '该路径不允许通过代理转发')
  if (isRateLimited(ip, 'api'))
    return sendJson(res, 429, '请求过于频繁，请稍后再试')

  return relay(req, res, target, {
    timeout: API_TIMEOUT,
    headers: proxyHeaders(req),
    body: req.method === 'POST' ? req : undefined,
    copy: ['content-type', 'content-encoding', 'content-length', 'retry-after', 'x-request-id'],
    timeoutMessage: '代理请求超时',
    failureMessage: '代理无法连接目标服务',
  })
}

const server = http.createServer((req, res) => {
  let url
  try {
    url = new URL(req.url, 'http://localhost')
  }
  catch {
    return res.writeHead(400).end()
  }
  if (CLIENT_TIMEOUT !== null && url.pathname === '/__tmo.js') {
    res.writeHead(200, { 'cache-control': 'no-store', 'content-type': 'text/javascript; charset=utf-8', 'x-content-type-options': 'nosniff' })
    res.end(req.method === 'HEAD' ? undefined : `window.__TMO=${CLIENT_TIMEOUT}`)
    return
  }
  if (url.pathname === '/api/proxy') {
    handleProxy(req, res).catch((error) => {
      console.error('proxy error:', error)
      if (!res.headersSent)
        sendJson(res, 502, '代理无法连接目标服务')
      else res.destroy()
    })
    return
  }
  serveStatic(req, res, url.pathname).catch((error) => {
    if (error.code === 'ERR_STREAM_PREMATURE_CLOSE')
      return
    console.error('static error:', error)
    if (!res.headersSent) {
      res.writeHead(500, { 'content-type': 'text/plain; charset=utf-8' })
      res.end('Internal Server Error')
    }
    else {
      res.destroy()
    }
  })
})

server.listen(PORT, HOST, () => {
  console.warn(`PoseWear listening on http://${HOST}:${PORT}`)
  console.warn(`timeouts (ms): api=${API_TIMEOUT || 'none'} image=${IMAGE_TIMEOUT || 'none'} client=${CLIENT_TIMEOUT ?? 'upstream default'}`)
})

function shutdown() {
  server.close(() => process.exit(0))
  setTimeout(() => process.exit(0), 5000).unref()
}
process.on('SIGINT', shutdown)
process.on('SIGTERM', shutdown)
