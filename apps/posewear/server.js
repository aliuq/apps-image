/** Parse the Cloudflare Pages `_headers` file generated by the upstream build. */
function parseHeaderRules(file) {
  let text
  try {
    text = fs.readFileSync(file, 'utf8')
  }
  catch {
    return []
  }
  const rules = []
  let current
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/\s+$/, '')
    if (!line || line.startsWith('#'))
      continue
    if (!/^\s/.test(line)) {
      current = { pattern: line.trim(), headers: [] }
      rules.push(current)
      continue
    }
    const colon = line.indexOf(':')
    if (colon < 0 || !current)
      continue
    current.headers.push([
      line.slice(0, colon).trim().toLowerCase(),
      line.slice(colon + 1).trim(),
    ])
  }
  return rules
}

const HEADER_RULES = parseHeaderRules(path.join(ROOT, '_headers'))

function matchesHeaderPattern(pattern, pathname) {
  if (pattern === '/*')
    return true
  if (pattern.endsWith('/*'))
    return pathname.startsWith(pattern.slice(0, -1))
  return pathname === pattern
}

function applyHeaderRules(res, pathname) {
  for (const rule of HEADER_RULES) {
    if (!matchesHeaderPattern(rule.pattern, pathname))
      continue
    for (const [name, value] of rule.headers) {
      if (name === 'content-security-policy') {
        // The upstream policy is written for HTTPS. Docker deployments commonly
        // run on plain HTTP, where upgrading same-origin requests breaks the site.
        res.setHeader(name, value.replace(/;\s*upgrade-insecure-requests/gi, ''))
      }
      else {
        res.setHeader(name, value)
      }
    }
  }
}

function sendJson(res, status, message) {
  const body = JSON.stringify({ error: { message } })
  res.writeHead(status, {
    'cache-control': 'no-store',
    'content-length': Buffer.byteLength(body),
    'content-type': 'application/json; charset=utf-8',
  })
  res.end(body)
}

async function sendNotFound(req, res, pathname) {
  applyHeaderRules(res, pathname)
  res.setHeader('cache-control', 'no-cache')
  let body
  try {
    body = await fsp.readFile(path.join(ROOT, '404.html'))
  }
  catch {
    body = Buffer.from('Not Found')
  }
  res.setHeader('content-type', 'text/html; charset=utf-8')
  res.setHeader('content-length', body.length)
  res.writeHead(404)
  res.end(req.method === 'HEAD' ? undefined : body)
}

async function serveStatic(req, res, pathname) {
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    res.writeHead(405, { allow: 'GET, HEAD' })
    res.end()
    return
  }
  if (pathname === '/_headers' || pathname.startsWith('/.')) {
    await sendNotFound(req, res, pathname)
    return
  }

  let decoded
  try {
    decoded = decodeURIComponent(pathname)
  }
  catch {
    res.writeHead(400)
    res.end()
    return
  }
  if (decoded.includes('\0')) {
    res.writeHead(400)
    res.end()
    return
  }

  let file = path.resolve(ROOT, `.${decoded}`)
  if (file !== ROOT && !file.startsWith(`${ROOT}${path.sep}`)) {
    await sendNotFound(req, res, pathname)
    return
  }
  const rel = path.relative(ROOT, file)
  if (
    rel.startsWith('..')
    || path.isAbsolute(rel)
    || rel.split(path.sep).some(part => part.startsWith('.'))
    || rel === '_headers'
  ) {
    await sendNotFound(req, res, pathname)
    return
  }

  let stat
  try {
    stat = await fsp.stat(file)
  }
  catch {
    await sendNotFound(req, res, pathname)
    return
  }

  if (stat.isDirectory()) {
    if (!pathname.endsWith('/')) {
      const search = new URL(req.url, 'http://localhost').search
      res.writeHead(301, { location: `${pathname}/${search}` })
      res.end()
      return
    }
    file = path.join(file, 'index.html')
    try {
      stat = await fsp.stat(file)
    }
    catch {
      await sendNotFound(req, res, pathname)
      return
    }
  }

  applyHeaderRules(res, pathname)
  const etag = `W/"${stat.size.toString(16)}-${Math.floor(stat.mtimeMs).toString(16)}"`
  res.setHeader('etag', etag)
  res.setHeader('last-modified', stat.mtime.toUTCString())
  if (req.headers['if-none-match'] === etag) {
    res.writeHead(304)
    res.end()
    return
  }

  const type = MIME.get(path.extname(file).toLowerCase()) || 'application/octet-stream'
  const compressible = /^(?:text\/|application\/(?:json|javascript|manifest\+json|xml))/.test(type)
  const useGzip = compressible && stat.size > 1024 && req.method !== 'HEAD' && /\bgzip\b/.test(req.headers['accept-encoding'] || '')
  if (!res.hasHeader('cache-control'))
    res.setHeader('cache-control', 'public, max-age=600')
  res.setHeader('content-type', type)
  if (compressible)
    res.setHeader('vary', 'accept-encoding')
  if (useGzip) {
    const body = await gzip(await fsp.readFile(file))
    res.setHeader('content-encoding', 'gzip')
    res.setHeader('content-length', body.length)
    res.writeHead(200)
    res.end(body)
    return
  }
  res.setHeader('content-length', stat.size)
  res.writeHead(200)
  if (req.method === 'HEAD') {
    res.end()
    return
  }
  await pipeline(fs.createReadStream(file), res)
}

function sameSite(req) {
  const host = req.headers.host
  if (!host)
    return false
  for (const name of ['origin', 'referer']) {
    const value = req.headers[name]
    if (!value)
      continue
    try {
      return new URL(value).host.toLowerCase() === host.toLowerCase()
    }
    catch {
      return false
    }
  }
  return false
}

function clientIp(req) {
  const forwarded = String(req.headers['x-forwarded-for'] || '').split(',')[0].trim()
  return String(req.headers['cf-connecting-ip'] || forwarded || req.headers['x-real-ip'] || req.socket.remoteAddress || '0')
}

function isPrivateHost(hostname) {
  const host = hostname.toLowerCase()
  if (host === 'localhost' || host.endsWith('.localhost') || host.endsWith('.local') || host.endsWith('.internal'))
    return true
  if (host === '0.0.0.0' || host === '::1' || host.startsWith('['))
    return true
  const parts = host.split('.')
  if (parts.length === 4 && parts.every(p => /^\d+$/.test(p))) {
    const a = Number(parts[0])
    const b = Number(parts[1])
    if (a === 0 || a === 10 || a === 127)
      return true
    if (a === 169 && b === 254)
      return true
    if (a === 172 && b >= 16 && b <= 31)
      return true
    if (a === 192 && b === 168)
      return true
  }
  return false
}

const rate = new Map()
function isRateLimited(ip, kind) {
  const now = Date.now()
  const key = `${kind}|${ip}`
  let entry = rate.get(key)
  if (!entry || now - entry.start > 60_000) {
    entry = { start: now, count: 0 }
    rate.set(key, entry)
  }
  entry.count += 1
  if (rate.size > 5000) {
    for (const [k, v] of rate) {
      if (now - v.start > 60_000)
        rate.delete(k)
    }
  }
  return entry.count > (kind === 'image' ? 40 : 20)
}

function proxyHeaders(req) {
  const headers = new Headers()
  for (const [name, value] of Object.entries(req.headers)) {
    const key = name.toLowerCase()
    if (DROP_HEADERS.has(key) || key.startsWith('cf-') || key.startsWith('proxy-'))
      continue
    if (Array.isArray(value)) {
      for (const item of value) headers.append(name, item)
    }
    else if (value !== undefined) {
      headers.set(name, value)
    }
  }
  return headers
}

async function streamUpstream(upstream, res) {
  if (upstream.body) {
    await pipeline(Readable.fromWeb(upstream.body), res)
  }
  else {
    res.end()
  }
}

async function handleProxy(req, res) {
  if (req.method === 'OPTIONS') {
    res.writeHead(204, { allow: 'GET, POST, OPTIONS' })
    res.end()
    return
  }
  if (req.method !== 'GET' && req.method !== 'POST') {
    sendJson(res, 405, '只支持 GET / POST')
    return
  }
  if (!sameSite(req)) {
    sendJson(res, 403, '只接受本站页面发起的请求')
    return
  }

  let target
  try {
    target = new URL(String(req.headers['x-target-url'] || ''))
  }
  catch {
    sendJson(res, 400, '缺少或无效的 x-target-url')
    return
  }
  if (target.protocol !== 'https:' || target.username || target.password || (target.port && target.port !== '443')) {
    sendJson(res, 400, '目标地址必须是标准 https 地址')
    return
  }

  const ip = clientIp(req)
  if (req.headers['x-proxy-kind'] === 'image') {
    if (req.method !== 'GET') {
      sendJson(res, 405, '图片下载只支持 GET')
      return
    }
    if (!IMAGE_HOSTS.some(r => r.test(target.hostname))) {
      sendJson(res, 403, '该图片地址不在允许范围内')
      return
    }
    if (isRateLimited(ip, 'image')) {
      sendJson(res, 429, '请求过于频繁，请稍后再试')
      return
    }
    const controller = new AbortController()
    const timer = setTimeout(() => controller.abort(), IMAGE_TIMEOUT)
    req.on('aborted', () => controller.abort())
    try {
      const upstream = await fetch(target, { redirect: 'manual', signal: controller.signal })
      const type = upstream.headers.get('content-type') || ''
      if (!upstream.ok || !/^image\//i.test(type)) {
        await upstream.body?.cancel()
        sendJson(res, 502, '结果图片下载失败')
        return
      }
      res.writeHead(upstream.status, {
        'cache-control': 'no-store',
        'content-type': type,
        'x-content-type-options': 'nosniff',
      })
      await streamUpstream(upstream, res)
    }
    catch (error) {
      if (!res.headersSent) {
        const timeout = error.name === 'AbortError'
        sendJson(res, timeout ? 504 : 502, timeout ? '图片下载超时' : '结果图片下载失败')
      }
      else {
        res.destroy()
      }
    }
    finally {
      clearTimeout(timer)
    }
    return
  }

  const official = OFFICIAL_HOSTS.some(r => r.test(target.hostname))
  const custom = req.headers['x-proxy-custom'] === '1'
  if (!official && !custom) {
    sendJson(res, 403, '该地址不是官方接口；自定义中转需在设置中选择「自定义」')
    return
  }
  const targetPath = target.pathname.replace(/\/+$/, '')
  if (official ? !API_PATH.test(targetPath) : !CUSTOM_PATH.test(targetPath)) {
    sendJson(res, 403, '该路径不允许通过代理转发')
    return
  }
  if (custom && isPrivateHost(target.hostname)) {
    sendJson(res, 403, '不能转发到内网地址')
    return
  }
  if (isRateLimited(ip, 'api')) {
    sendJson(res, 429, '请求过于频繁，请稍后再试')
    return
  }

  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), API_TIMEOUT)
  req.on('aborted', () => controller.abort())
  try {
    const init = {
      headers: proxyHeaders(req),
      method: req.method,
      redirect: 'manual',
      signal: controller.signal,
    }
    if (req.method === 'POST') {
      init.body = req
      init.duplex = 'half'
    }
    const upstream = await fetch(target, init)
    const headers = { 'cache-control': 'no-store' }
    const type = upstream.headers.get('content-type')
    if (type)
      headers['content-type'] = type
    res.writeHead(upstream.status, headers)
    await streamUpstream(upstream, res)
  }
  catch (error) {
    if (!res.headersSent) {
      const timeout = error.name === 'AbortError'
      sendJson(res, timeout ? 504 : 502, timeout ? '代理请求超时' : '代理无法连接目标服务')
    }
    else {
      res.destroy()
    }
  }
  finally {
    clearTimeout(timer)
  }
}

const server = http.createServer((req, res) => {
  let url
  try {
    url = new URL(req.url, 'http://localhost')
  }
  catch {
    res.writeHead(400)
    res.end()
    return
  }
  if (url.pathname === '/api/proxy') {
    handleProxy(req, res).catch((error) => {
      console.error('proxy error:', error)
      if (!res.headersSent)
        sendJson(res, 502, '代理无法连接目标服务')
      else res.destroy()
    })
    return
  }
  serveStatic(req, res, url.pathname).catch((error) => {
    console.error('static error:', error)
    if (!res.headersSent) {
      res.writeHead(500, { 'content-type': 'text/plain; charset=utf-8' })
      res.end('Internal Server Error')
    }
    else {
      res.destroy()
    }
  })
})

server.listen(PORT, HOST, () => {
  console.warn(`PoseWear listening on http://${HOST}:${PORT}`)
})

function shutdown() {
  server.close(() => process.exit(0))
  setTimeout(() => process.exit(0), 5000).unref()
}
process.on('SIGINT', shutdown)
process.on('SIGTERM', shutdown)
