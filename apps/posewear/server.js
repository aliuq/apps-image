/** 读取毫秒级超时环境变量；0 表示永不超时，为空或非法时使用默认值。 */
function timeoutFromEnv(name, fallback) {
  const raw = process.env[name]
  if (raw === undefined || raw === '')
    return fallback
  const value = /^\d+$/.test(raw) ? Number(raw) : Number.NaN
  // setTimeout 超过 2^31-1 会被 Node 截断为 1ms，直接视为非法。
  if (!Number.isSafeInteger(value) || value > MAX_TIMEOUT) {
    console.warn(`invalid ${name}=${raw}, using ${fallback}ms (0 disables the timeout)`)
    return fallback
  }
  return value
}

